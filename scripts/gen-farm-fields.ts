// Generates src/farm/FarmFields.ts: the table of every crop field (planned by src/farm/FarmPlan.ts on the real terrain).
// The plan takes ~20 s, so it is NOT run in the game: the table is committed and tree / grass / rock placement can use it in the chunk workers.
//   npm run gen:farm        (re-run when the terrain, roads or building placements change; npm run test:farm checks the table is current)
import { writeFileSync } from 'node:fs';
import { TerrainGenerator } from '../src/terrain/TerrainGenerator';
import { Config } from '../src/core/Config';
import { terrainGround } from '../src/farm/FarmGround';
import { planFarms } from '../src/farm/FarmPlan';
import { CROPS } from '../src/farm/CropDefs';

const ENVS = ['paddy', 'lowland', 'upland', 'hill', 'homestead'];
const KINDS = ['plot', 'garden', 'hill'];
const g = new TerrainGenerator(Config.world.seed);
const fields = planFarms(terrainGround(g), Config.world.seed);
const r = (v: number, n: number) => Number(v.toFixed(n));
const rows = fields.map((f) => `[${r(f.cx, 1)},${r(f.cz, 1)},${r(f.yaw, 3)},${r(f.w, 1)},${r(f.d, 1)},${r(f.y, 2)},${r(f.relief, 1)},${f.level ? 1 : 0},${KINDS.indexOf(f.kind)},${ENVS.indexOf(f.env)},${CROPS.findIndex((c) => c.id === f.crop)},${f.stage},${r(f.progress, 2)},${f.act},${f.seed},'${f.zone}']`);
const out = `// GENERATED by scripts/gen-farm-fields.ts - do not edit by hand. ${fields.length} crop fields (world seed ${Config.world.seed}).
// Row: cx, cz, yaw, w, d, y, relief, level, kind, env, crop (index in CROPS), stage, progress, act, seed, zone.
// Pure data (no three.js): the chunk workers use FARM_INDEX to keep trees, rocks and grass off the crops.
import { CROPS } from './CropDefs';
import { FieldIndex, type Field, type FieldKind } from './FarmPlan';

const ENVS = ${JSON.stringify(ENVS)} as const;
const KINDS = ${JSON.stringify(KINDS)} as const;
type Row = [number, number, number, number, number, number, number, number, number, number, number, number, number, number, number, string];
const ROWS: Row[] = [
${rows.join(',\n')},
];

export const FARM_FIELDS: readonly Field[] = ROWS.map((r, id) => ({
  id, cx: r[0], cz: r[1], yaw: r[2], w: r[3], d: r[4], y: r[5], relief: r[6], level: r[7] === 1,
  kind: KINDS[r[8]] as FieldKind, env: ENVS[r[9]], crop: CROPS[r[10]].id, stage: r[11], progress: r[12], act: r[13], seed: r[14], zone: r[15],
}));
export const FARM_INDEX = new FieldIndex(FARM_FIELDS);
/** True when (x, z) is on a crop field (+ margin m): trees, rocks and grass keep away. */
export const farmCovers = (x: number, z: number, margin = 0): boolean => FARM_INDEX.covers(x, z, margin);
`;
writeFileSync(new URL('../src/farm/FarmFields.ts', import.meta.url), out);
console.log(`wrote src/farm/FarmFields.ts: ${fields.length} fields`);
